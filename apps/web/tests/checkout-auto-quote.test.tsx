import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { PurchaseFlow } from '../components/checkout/purchase-flow';
import { calculateQuote } from '../services/quote.service';
const { lines } = vi.hoisted(() => ({ lines: [{ key: 'l', productId: 'p', sizeId: 's', name: 'Latte', sizeName: 'M', toppings: [], note: '', quantity: 1, unitPrice: 35000, imageUrl: null }] }));
vi.mock('next/navigation', () => ({ useRouter: () => ({ push: vi.fn() }) }));
vi.mock('../components/cart/cart-provider', () => ({ useCart: () => ({ lines, subtotal: 35000, version: 1, ready: true, canCheckout: true, reload: vi.fn() }) }));
vi.mock('../services/auth.service', () => ({ currentUser: async () => ({ id: 'u', fullName: 'Customer', email: 'test@example.test', loyaltyPoints: 100 }), authError: () => 'Error' }));
vi.mock('../services/quote.service', () => ({ calculateQuote: vi.fn() }));
vi.mock('../services/checkout.service', () => ({ pendingCheckout: () => null, createCheckoutOrder: vi.fn() }));
Object.defineProperty(HTMLDialogElement.prototype, 'showModal', { configurable: true, value: function (this: HTMLDialogElement) { this.setAttribute('open', ''); } });
Object.defineProperty(HTMLDialogElement.prototype, 'close', { configurable: true, value: function (this: HTMLDialogElement) { this.removeAttribute('open'); } });
afterEach(() => { cleanup(); vi.clearAllMocks(); });
const quote = { items: [], subtotal: '35000', discountAmount: '0', pointsDiscount: '0', finalTotal: '35000', quoteFingerprint: 'f' };
it('quotes automatically, debounces coupon edits and invalidates confirmation immediately', async () => {
  vi.mocked(calculateQuote).mockResolvedValue(quote);
  render(<PurchaseFlow onClose={vi.fn()} />);
  await screen.findByText('Tổng thanh toán: 35.000đ');
  expect(screen.queryByRole('button', { name: 'Tính lại tổng đơn' })).toBeNull();
  const coupon = screen.getByLabelText('Mã giảm giá');
  fireEvent.change(coupon, { target: { value: 'A' } }); fireEvent.change(coupon, { target: { value: 'ABC' } });
  expect(screen.queryByRole('button', { name: 'Xác nhận mua' })).toBeNull();
  await waitFor(() => expect(calculateQuote).toHaveBeenLastCalledWith(lines, 'ABC', 0));
  expect(calculateQuote).toHaveBeenCalledTimes(2);
  fireEvent.change(screen.getByLabelText(/Dùng điểm thưởng/), { target: { value: '10' } });
  await waitFor(() => expect(calculateQuote).toHaveBeenLastCalledWith(lines, 'ABC', 10));
});
it('ignores an older response arriving after a newer quote and retries API failures', async () => {
  let resolveOld!: (value: typeof quote) => void;
  vi.mocked(calculateQuote).mockImplementationOnce(() => new Promise((resolve) => { resolveOld = resolve; })).mockResolvedValueOnce({ ...quote, finalTotal: '30000' }).mockRejectedValueOnce(new Error('Mã không hợp lệ')).mockResolvedValue(quote);
  render(<PurchaseFlow onClose={vi.fn()} />);
  await waitFor(() => expect(calculateQuote).toHaveBeenCalledTimes(1));
  fireEvent.change(screen.getByLabelText('Mã giảm giá'), { target: { value: 'NEW' } });
  await screen.findByText('Tổng thanh toán: 30.000đ'); resolveOld(quote);
  await waitFor(() => expect(screen.queryByText('Tổng thanh toán: 35.000đ')).toBeNull());
  fireEvent.change(screen.getByLabelText('Mã giảm giá'), { target: { value: 'BAD' } });
  await screen.findByText(/Mã không hợp lệ/); expect(screen.queryByRole('button', { name: 'Xác nhận mua' })).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Thử lại' })); await screen.findByText('Tổng thanh toán: 35.000đ');
});
